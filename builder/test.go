type TestAttrs struct {
	ImportPath string
	Srcs       []string
	XSrcs      []string
	Data       string
}

type importPackage struct {
	Name string
	Path string
}

type testCase struct {
	Package string
	Name    string
}

type example struct {
	testCase
	Output    string
	Unordered bool
}

type testPackage struct {
	ImportPath   string
	SupportsFuzz bool
	Imports      []importPackage

	Tests       []testCase
	Benchmarks  []testCase
	FuzzTargets []testCase
	Examples    []example

	TestMain string

	Data string
}

